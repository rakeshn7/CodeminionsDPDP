def validate_verhoeff(number_str: str) -> bool:
    """Validate a numeric string using the Verhoeff checksum algorithm (used by UIDAI Aadhaar)."""
    digits = [int(c) for c in number_str if c.isdigit()]
    if not digits:
        return False
    c = 0
    for idx, digit in enumerate(reversed(digits)):
        p_val = _P_TABLE[idx % 8][digit]
        c = _D_TABLE[c][p_val]
    return c == 0
